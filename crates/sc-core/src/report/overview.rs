//! The top of a report: its header, summary and indicator table.

use super::{Audience, Report, agentness, audience, hosts_not_named, kind_label};
use crate::extract::defang;
use crate::model::{IndicatorKind, fmt_ts, top_counts};
use crate::notice::PublicView;
use std::collections::BTreeMap;
use std::fmt::Write;

impl Report<'_> {
    /// Title, draft banner, and what the report covers.
    pub(super) fn header(&self, s: &mut String) {
        let (a, opts, clusters) = (self.a, self.opts, &self.clusters);
        let title = audience::title(opts.audience);
        let _ = writeln!(s, "# {title}\n");
        let _ = writeln!(
            s,
            "> **DRAFT** — generated by swarmchase. Verify every item against the public records before sending.\n"
        );
        if let Some(g) = &opts.generated {
            let _ = writeln!(s, "- **Prepared:** {g}");
        }
        if let Some(r) = &opts.reporter {
            let _ = writeln!(s, "- **Reporter:** {r}");
        }
        let start = clusters
            .iter()
            .map(|c| c.start)
            .filter(|&t| t > 0)
            .min()
            .unwrap_or(a.timing.start);
        let end = clusters.iter().map(|c| c.end).max().unwrap_or(a.timing.end);
        let n_obs: usize = clusters.iter().map(|c| c.members.len()).sum();
        let tier = clusters.iter().map(|c| c.tier).max().unwrap_or_default();
        let _ = writeln!(s, "- **Window:** {} → {}", fmt_ts(start), fmt_ts(end));
        let _ = writeln!(
            s,
            "- **Records:** {n_obs} linked public records in {} cluster(s) (of {} records reviewed, {} flagged)",
            clusters.len(),
            a.total,
            a.flagged
        );
        let _ = writeln!(s, "- **Evidence tier:** {}", tier.label());
        let _ = writeln!(
            s,
            "- **Method:** swarmchasing {}, rules version {}\n",
            env!("CARGO_PKG_VERSION"),
            a.rules_version
        );
    }

    /// The summary. Returns the target hosts it may name, with their
    /// records, and how many it left unnamed (a public notice names only the
    /// hosts the admin classified as affected).
    pub(super) fn summary(
        &self,
        s: &mut String,
        view: Option<&mut PublicView>,
    ) -> (BTreeMap<String, usize>, usize) {
        let opts = self.opts;
        let _ = writeln!(s, "## Summary\n");
        let mut hosts: BTreeMap<String, usize> = BTreeMap::new();
        let mut kinds: BTreeMap<IndicatorKind, usize> = BTreeMap::new();
        for c in &self.clusters {
            for (h, n) in &c.target_hosts {
                *hosts.entry(h.clone()).or_default() += n;
            }
            for (k, n) in &c.kinds {
                *kinds.entry(*k).or_default() += n;
            }
        }
        let unnamed = match view.as_deref() {
            Some(v) => {
                let before = hosts.len();
                hosts.retain(|h, _| v.named(h));
                before - hosts.len()
            }
            None => 0,
        };
        if let Some(v) = view {
            v.note_unnamed(unnamed);
        }
        let mut host_list: Vec<String> = top_counts(&hosts, 5)
            .into_iter()
            .map(|(h, n)| {
                format!(
                    "`{}` ({n})",
                    defang(&format!("https://{h}")).trim_start_matches("hxxps://")
                )
            })
            .collect();
        if unnamed > 0 {
            host_list.push(hosts_not_named(unnamed));
        }
        let _ = writeln!(
            s,
            "{}",
            audience::summary(opts.audience, &host_list, opts.reported.as_ref())
        );
        if kinds.contains_key(&IndicatorKind::Exploit) {
            let _ = writeln!(
                s,
                "\n**Attack payloads were present** (see Indicators). We did not test whether they succeeded.{}",
                if opts.audience == Audience::Public {
                    agentness::public_note(&self.clusters, opts)
                } else {
                    ""
                }
            );
        }
        let _ = writeln!(s);
        (hosts, unnamed)
    }

    /// Records per rule, by evidence kind.
    pub(super) fn indicators(&self, s: &mut String) {
        let _ = writeln!(s, "## Indicators\n");
        let _ = writeln!(s, "| Category | Rule | Records |\n|---|---|---|");
        let mut rule_rows: BTreeMap<(IndicatorKind, String), usize> = BTreeMap::new();
        for c in &self.clusters {
            for &m in &c.members {
                for h in &self.a.results[m].hits {
                    *rule_rows.entry((h.kind, h.rule_id.clone())).or_default() += 1;
                }
            }
        }
        for ((k, id), n) in &rule_rows {
            let _ = writeln!(s, "| {} | `{id}` | {n} |", kind_label(*k));
        }
        let _ = writeln!(s);
    }
}
